# --- super() past an instance override ---------------------------------------------------


class _Base:
    def load(self, pid):
        raise KeyError('base')


class _Sub(_Base):
    def load(self, pid):
        raise AssertionError('never')

    def _load(self, pid):
        try:
            super().load(pid)
        except KeyError as e:
            return 'base raised %s' % e


# Patching a PLAIN _Base instance first is what put the self-send dispatcher
# on _Base, which super() then found.
