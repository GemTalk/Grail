# Runtime gaps that CPython's test_pickle exposed, beyond pickle itself.
#
# Each section is one defect.  test_pickle hit it through pickle, but none of
# them is a pickle bug, and each had a symptom of its own outside it:
#
#   * os.path's Smalltalk dirname/basename/split/splitext/normpath disagreed
#     with posixpath on ordinary inputs -- dirname('a.txt') was '.', so
#     http.server's translate_path skipped every URL component, and
#     split('/a') was ('', 'a').  A bytes argument ended the session.
#   * sys.intern answered a fresh string each call, and an instance __dict__
#     handed out a fresh key string on each read.
#   * A builtin method reached through a kernel implementation class named it:
#     str.index was 'CharacterCollection.index' in module
#     'CharacterCollection'.  A method a Python class inherits from a builtin
#     was a different object from the builtin's own.
#   * del f.__module__ raised AttributeError.
#   * os.stat_result was a plain object: not indexable, not comparable, not
#     picklable, and os.stat_result(...) could not be called.
#   * A str holding a lone surrogate had no replace / split / find / strip /
#     ... at all, and bytes(s, enc), getattr(module, s) and __import__(s)
#     each failed on one.
#   * super().m() from inside an instance override of m looped, once any
#     instance of the base had had m overridden.
#   * A @staticmethod / @classmethod read from the class __dict__ was the bare
#     function rather than the descriptor object.
#   * defaultdict and OrderedDict borrowed dict's repr, which made pprint
#     print every plain dict as a defaultdict once method identity was fixed.
#   * Error messages named the Grail class BoundMethod, and an empty attribute
#     name read "X object has no attribute (empty name)".
#   * urllib.request.urlretrieve, http.server's SimpleHTTPRequestHandler /
#     CGIHTTPRequestHandler and mimetypes.guess_file_type were missing.
#
# EXPECTED was generated by RUNNING CPython 3.14.6 (``--emit``).

