def _unlink(path):
    """os.remove, falling back to the shell.  Under CPython the fallback never
    runs; under Grail it is what removes a ``$'' path, whose removal goes to the
    same expanding primitive as its creation.  Stated here rather than hidden,
    because a teardown that silently left files behind is how the os.walk work
    started."""
    try:
        os.remove(path)
    except OSError:
        os.system("rm -f '" + path + "'")


def _teardown():
    for dirpath, dirnames, filenames in os.walk(ROOT, topdown=False):
        for name in filenames:
            _unlink(J(dirpath, name))
        for name in dirnames:
            p = J(dirpath, name)
            _unlink(p) if os.path.islink(p) else os.rmdir(p)
    os.rmdir(ROOT)


_teardown()


