# EINVAL, not ENOENT: there IS something there, it is just not a link.
rec('readlink_on_a_regular_file', lambda: os.readlink(J(ROOT, 'f.txt')))
rec('readlink_on_a_missing_path', lambda: os.readlink(J(ROOT, 'nope')))


