def _teardown():
    for dirpath, dirnames, filenames in os.walk(ROOT, topdown=False):
        for name in filenames:
            os.remove(J(dirpath, name))
        for name in dirnames:
            p = J(dirpath, name)
            os.remove(p) if os.path.islink(p) else os.rmdir(p)
    os.rmdir(ROOT)


