# shutil.copystat / os.chmod / archive extraction -- METADATA, read back.
#
# WHAT THIS EXISTS TO STOP.  os.utime shipped before this as a real call that
# nothing used: shutil.copystat was a "return None" and tarfile.extract wrote
# bytes and no attributes.  Half the reason was honest -- there was no os.chmod
# -- but the shape of the gap is the dangerous kind, because "copy2() copied
# the metadata" is a thing callers BELIEVE rather than check.  os.chmod now
# exists, and copystat/copy2/copytree and tarfile.extract use it and os.utime.
#
# EVERY POSITIVE CHECK BELOW READS THE METADATA BACK with os.stat.  None of
# them is satisfied by a call that merely fails to raise -- that is the lesson
# the os.utime lane paid for: a no-op os.utime passed 4 of its 13 tests,
# because a file that has just been created already HAS "now" for an mtime, so
# "set it to now and see" cannot tell setting from not setting.  So:
#
#   * every mtime asserted here is a FIXED INSTANT YEARS IN THE PAST (2001,
#     2004, 2008, 2011), never "now" and never "the time the file was made";
#   * every mode asserted here DIFFERS from what the file would have got from
#     open() under a normal umask.  0o644 is useless as evidence for exactly
#     that reason and appears nowhere as an expected value; the modes used are
#     0o600 (more restrictive than the default) and 0o755 (more permissive),
#     plus 0o777 and 0o4755 in the archive, which must NOT survive.
#
# THE RESTRICTIVE DIRECTION IS THE ONE THAT MATTERS.  A chmod bug that leaves
# a file MORE permissive than asked is a security answer, not a wrong one, so
# the checks are written to catch that specifically: copying a 0o600 file's
# mode onto a 0o666 destination must end at 0o600, and an archive member
# claiming 0o777 or setuid must come out at 0o755 with the setuid bit gone.
#
# SHELL QUOTING.  Grail has no chmod(2) or utimes(2) -- os.chmod and os.utime
# run chmod(1) and touch(1) -- so an archive member's NAME reaches a command
# line.  One member of the tar fixture is named
#
#     m/od'd ; touch grail_extract_pwned_marker ; x.txt
#
# and the checks are not only that its mode and mtime landed but that the
# marker file the semicolons would have created does not exist.  Note that the
# usual ``--'' guard is NOT what protects it: BSD chmod does not implement
# ``--'' at all (measured on macOS 26.6, where ``chmod 0600 -- f'' reports
# ``chmod: --: No such file or directory'' and chmods f anyway), so os.chmod
# prefixes a leading-dash path with ``./'' instead, which needs no cooperation
# from the utility.  chmod_leading_dash_name below is the check for that.
#
# ZIPFILE RESTORES NOTHING, ON PURPOSE.  CPython's ZipFile._extract_member
# writes the file and stops: no chmod, no utime, anywhere in CPython's
# zipfile.  So the zip checks here assert that the recorded mode and date_time
# are IGNORED.  That is conformance; wiring them up would be the deviation.
#
# WHOLE SECONDS.  Grail's os.stat answers an int st_mtime where CPython
# answers a float, so everything here compares int(st.st_mtime).
#
# The two archives are produced by CPython's own tarfile/zipfile;
# tests/scripts/make_archive_fixtures.py regenerates them and its --check mode
# (run by ci.yml) fails if the hex below is hand-edited.
#
# EXPECTED was generated by RUNNING CPython 3.14.6.

