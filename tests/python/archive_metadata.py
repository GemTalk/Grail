def _rmtree(path):
    for name in os.listdir(path):
        p = J(path, name)
        if os.path.isdir(p):
            _rmtree(p)
        else:
            os.remove(p)
    os.rmdir(path)


def _chmod_all(path):
    os.chmod(path, 0o700)
    for name in os.listdir(path):
        p = J(path, name)
        if os.path.isdir(p):
            _chmod_all(p)
        else:
            os.chmod(p, 0o600)


def _teardown():
    # Everything was chmod'ed on the way through, including a 0o400 file and a
    # 0o700 directory, so make the tree writable again before removing it.
    _chmod_all(ROOT)
    _rmtree(ROOT)
    for d in PWNED_DIRS:
        if os.path.exists(J(d, MARKER)):
            os.remove(J(d, MARKER))


