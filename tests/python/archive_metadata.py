# Fixed instants, none of them "now": 2001-09-09, 2004-11-09, 2008-01-19,
# 2009-02-13, 2012-10-13.  A no-op utime leaves the file's creation time,
# which is none of these.
T_A = 1000000000
T_B = 1100000000
T_C = 1200000000
T_D = 1250000000
T_DIR = 1300000000
T_HOSTILE = 1350000000


def imode(path):
    return stat.S_IMODE(os.stat(path).st_mode)


def mtime(path):
    return int(os.stat(path).st_mtime)


def write(path, text, mode=None):
    f = open(path, 'w')
    f.write(text)
    f.close()
    if mode is not None:
        os.chmod(path, mode)
    return path


def unhex(h):
    return bytes.fromhex(h)


# ---------------------------------------------------------------- os.chmod

CH = J(ROOT, 'chmod')
os.mkdir(CH)

_p = write(J(CH, 'f.txt'), 'x')
rec('chmod_returns_none', lambda: os.chmod(_p, 0o600))
rec('chmod_restrictive', lambda: oct(imode(_p)))
os.chmod(_p, 0o755)
rec('chmod_permissive', lambda: oct(imode(_p)))
# A file left group/other-writable, then locked down: the direction a bug
# would silently skip.
os.chmod(_p, 0o666)
os.chmod(_p, 0o600)
rec('chmod_666_down_to_600', lambda: oct(imode(_p)))
# High (file-type) bits are ignored, as chmod(2) ignores them under CPython.
