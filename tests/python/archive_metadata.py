# ------------------------------------------------------- shutil.copystat

CS = J(ROOT, 'copystat')
os.mkdir(CS)

_src = write(J(CS, 'src.txt'), 'source', 0o600)
os.utime(_src, (T_A, T_B))
# The destination starts WIDE OPEN and with a different time, so nothing here
# can pass by accident.
_dst = write(J(CS, 'dst.txt'), 'dest', 0o666)
os.utime(_dst, (T_C, T_C))

rec('copystat_returns_none', lambda: shutil.copystat(_src, _dst))
rec('copystat_mode', lambda: oct(imode(_dst)))
rec('copystat_mtime', lambda: mtime(_dst))
rec('copystat_atime', lambda: int(os.stat(_dst).st_atime))
# The one check whose only job is to fail a no-op: the destination's mode and
# mtime must have MOVED OFF what they were set to a moment ago.
rec('copystat_moved_dst_off_its_own_values',
    lambda: (imode(_dst) != 0o666, mtime(_dst) != T_C))

_src2 = write(J(CS, 'src2.txt'), 's2', 0o755)
os.utime(_src2, (T_A, T_A))
