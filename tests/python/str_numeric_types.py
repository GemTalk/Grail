def _flags(predicate):
    return ''.join('1' if getattr(chr(c), predicate)() else '0' for c in SAMPLE)


def named_examples():
    chars = ('\u00b2', '\u00bd', '\u2460', '\u216b', '\u4e09', '\u0663',
             '\U00011f51', '\U0001d7d9', '\u2070', '\u00bc', '\U00010d31', '7')
    return tuple((ascii(ch), ch.isdecimal(), ch.isdigit(), ch.isnumeric(),
                  ch.isalnum()) for ch in chars)


def whole_strings():
    return ('12\u00bd'.isnumeric(), '12\u00bd'.isdigit(), '\u00b2\u00b3'.isdigit(),
            '\u00b2\u00b3'.isdecimal(), 'a\u00b2'.isalnum(), 'x1'.isdigit(),
            ''.isdigit(), ''.isnumeric(), ''.isdecimal(), ''.isalnum())


def decimal_boundaries():
    return _flags('isdecimal')


def digit_boundaries():
    return _flags('isdigit')


def numeric_boundaries():
    return _flags('isnumeric')


def numerics_are_alphanumeric():
    # isalnum is isalpha or isnumeric.  Only the numeric half is checked: the
    # neighbours of these ranges include letters newer than the kernel's
    # isLetter, which Grail does not yet know (isalpha is a separate gap).
    numeric = [c for c in SAMPLE if chr(c).isnumeric()]
    return len(numeric), all(chr(c).isalnum() for c in numeric)


