def _inspect_isasyncgen():
    async def ag():
        yield 1

    async def co():
        pass

    def g():
        yield 1
    c = co()
    try:
        return (inspect.isasyncgen(ag()),
                inspect.isasyncgen(c),
                inspect.isasyncgen(g()))
    finally:
        c.close()


def _isgenerator_excludes_async_generators():
    # THE GRAIL HAZARD, mirrored from the coroutine case: all three are one
    # machinery underneath, and CPython's predicates are mutually exclusive.
    async def ag():
        yield 1

    def g():
        yield 1
    return (inspect.isgenerator(g()),
            inspect.isgenerator(ag()),
            inspect.iscoroutine(ag()))


