def sock_sendall_sends_more_than_one_write_worth():
    """64KiB is past a loopback send buffer, so this exercises the partial-write
    path: send answers a short count, sendall waits for writability and
    continues from where it stopped."""
    async def main():
        srv, address = _listener()
        cli = _client(address)
        loop = asyncio.get_running_loop()
        conn, _addr = await loop.sock_accept(srv)
        payload = bytes(bytearray(range(256))) * 256      # 65536 bytes

        async def drain():
            got = bytearray()
            while len(got) < len(payload):
                chunk = await loop.sock_recv(cli, 16384)
                if not chunk:
                    break
                got += chunk
            return bytes(got)

        reader = asyncio.ensure_future(drain())
        await loop.sock_sendall(conn, payload)
        got = await reader
        conn.close()
        cli.close()
        srv.close()
        return (len(got), got == payload)

    return asyncio.run(main())


