def a_nonblocking_connect_reports_in_progress():
    """The socket-level primitive underneath sock_connect: a non-blocking
    connect STARTS and says so, with EINPROGRESS rather than a failure.

    Grail reported a bare OSError here -- `connect failed: getpeername failed
    with Socket is not connected` -- which is the internal completion probe's
    complaint, not the connect's.  GemStone was doing the right thing all along:
    every socket it creates is non-blocking at the OS level and every connect is
    issued non-blocking, so `connectTo:on:timeoutMs: 0` starts one and polls
    once, which is exactly this."""
    srv, address = _listener()
    s = socket.socket()
    s.setblocking(False)
    try:
        s.connect(address)
        return 'connected immediately'
    except BlockingIOError as e:
        return ('BlockingIOError', e.errno == errno.EINPROGRESS)
    finally:
        s.close()
        srv.close()


rec('a_nonblocking_connect_reports_in_progress',
    a_nonblocking_connect_reports_in_progress)


def sock_connect_reports_a_refused_connection():
    """The failure path has to arrive as an exception rather than as a wait that
    never ends.  It is the case a writability-only wait gets wrong: a refused
    connect makes the socket READABLE and never writable, so a loop waiting only
    for writability hangs.  sock_connect waits for either."""
    async def main():
        loop = asyncio.get_running_loop()
        s = socket.socket()
        s.setblocking(False)
        try:
            await loop.sock_connect(s, ('127.0.0.1', 1))
            return 'connected?!'
        except OSError as e:
            return type(e).__name__
        finally:
            s.close()

    return asyncio.run(main())


rec('sock_connect_reports_a_refused_connection',
    sock_connect_reports_a_refused_connection)


def connect_ex_answers_a_code_rather_than_raising():
    """connect_ex has exactly one contract -- never raise -- and it was not
    being kept: a blocking connect_ex to a closed port RAISED `OSError: connect
    failed` instead of answering ECONNREFUSED.  It shares the classifier with
    connect now, so the two cannot disagree about what happened either."""
    srv, address = _listener()
    a = socket.socket()
    b = socket.socket()
    c = socket.socket()
    c.setblocking(False)
    try:
        blocking_open = a.connect_ex(address)
        blocking_refused = b.connect_ex(('127.0.0.1', 1))
        nonblocking_refused = c.connect_ex(('127.0.0.1', 1))
        # The BLOCKING refusal's code is only asserted to BE a code: the
        # connect has already resolved by then, so it is read from readiness
        # rather than from the primitive, and readiness for an errored socket is
        # platform-dependent.  The NON-BLOCKING one comes from the primitive's
        # own errno and so is portable.
        return (blocking_open,
                isinstance(blocking_refused, int) and blocking_refused != 0,
                nonblocking_refused in (errno.ECONNREFUSED, errno.EINPROGRESS))
    finally:
        a.close()
        b.close()
        c.close()
        srv.close()


rec('connect_ex_answers_a_code_rather_than_raising',
    connect_ex_answers_a_code_rather_than_raising)


def connect_progression():
    """How a non-blocking connect PROGRESSES, which is where Grail and CPython
    differ -- in timing, not in outcome.

    CPython: a second connect() on a connect already under way raises EALREADY,
    and a refused connect reports EINPROGRESS first and the refusal only once
    the socket is ready.  Grail's retry is a POLL of the same connect, so it
    resolves a step earlier: the retry answers None once connected, and a
    loopback refusal is already resolved by the time the first call classifies
    it.  Both reach the same place -- which is what sock_connect and connect_ex
    are tested on -- so this probe records the intermediate states, and the
    Smalltalk test pins Grail's.

    NOT IN `EXPECTED`, and deliberately so: CPython's own answer here is
    PLATFORM-dependent.  A refused loopback connect reports ConnectionRefusedError
    straight away on Linux and EINPROGRESS-then-refused on macOS, so there is no
    portable CPython value to compare against -- pinning either one would make
    this file disagree with CPython on the other platform.  (CI caught exactly
    that; the first version of this probe was emitted on macOS and failed on
    Linux.)  The final OUTCOMES are portable and are what the probes above
    check."""
    srv, address = _listener()
    a = socket.socket()
    a.setblocking(False)
    try:
        a.connect(address)
    except BlockingIOError:
        pass
    try:
        retry = a.connect(address)
        retry = 'None'
    except BlockingIOError as e:
        retry = 'BlockingIOError %s' % ('EALREADY' if e.errno == errno.EALREADY
                                        else 'EINPROGRESS' if e.errno == errno.EINPROGRESS
                                        else e.errno,)
    b = socket.socket()
    b.setblocking(False)
    try:
        b.connect(('127.0.0.1', 1))
        first_refused = 'no error'
    except ConnectionRefusedError:
        first_refused = 'ConnectionRefusedError'
    except BlockingIOError:
        first_refused = 'BlockingIOError'
    a.close()
    b.close()
    srv.close()
    return (retry, first_refused)


rec('connect_progression', connect_progression)


