def a_watcher_can_be_registered_by_file_descriptor():
    """CPython's tables are keyed by descriptor, and `loop.add_reader(
    sock.fileno(), cb)` is the spelling library code uses.  Grail's readiness
    events are keyed by socket rather than by descriptor, so the int has to be
    resolved back through _socket's fd registry -- and the registration must be
    the SAME one, or adding by fd and removing by socket would leak a watcher."""
    async def main():
        srv, address = _listener()
        cli = _client(address)
        loop = asyncio.get_running_loop()
        conn, _addr = await loop.sock_accept(srv)

        fired = loop.create_future()
        loop.add_reader(conn.fileno(),
                        lambda: fired.done() or fired.set_result('by fd'))
        cli.sendall(b'x')
        answer = await fired
        removed_by_socket = loop.remove_reader(conn)

        conn.close()
        cli.close()
        srv.close()
        return (answer, removed_by_socket)

    return asyncio.run(main())


