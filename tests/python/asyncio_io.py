# THE LOOP DOES I/O.
#
# The event loop Grail already had was the callback/timer half of asyncio: a
# ready queue, a timer heap, Future and Task, sleep and run.  Enough to
# schedule, not enough to serve -- there was no add_reader, no sock_recv, and
# so no way for a socket to wake it.  Networking went through the blocking
# socket module, which on a cooperative loop means the first read stops every
# other task.
#
# What closes the gap is that GemStone already had the hard half.  `Processor
# whenReadable: sock signal: aSemaphore` (and whenWritable:) is a per-socket
# readiness registry, and Grail's `select` was already built on it -- register
# every socket against one semaphore and wait, and the gem sleeps until the
# first one is ready while other green threads keep running.  So this is a
# wiring job: the loop waits inside `select` whenever a socket is registered,
# and the sock_* coroutines are the ordinary retry-on-BlockingIOError shape.
#
# THE PROBE THAT MATTERS MOST is `two_clients_served_concurrently`. Everything
# else here would also pass on a loop that ran each connection to completion
# before looking at the next one -- right bytes, wrong order.  Interleaving can
# only happen if a socket that is not ready really returns control to the
# scheduler and the scheduler really resumes someone else.
#
# The second most interesting is `a_timer_fires_while_waiting_on_io`: a loop
# that blocks in select with no timeout is easy to write by accident, and it
# passes every test except one where a timer has to beat an idle socket.
#
# NOT COVERED, because it does not exist yet: transports and protocols. There
# is no create_server / create_connection / StreamReader, so an ASGI server
# cannot be pointed at this loop unmodified -- see docs/Support_FastAPI.md.
#
# Everything below is ordinary CPython asyncio -- no Grail-specific spelling --
# which is what makes this usable as ground truth rather than a description of
# what Grail happens to do.
#
# EXPECTED was generated by RUNNING CPython 3.14.6.

import asyncio
import errno
import socket
import time

r = {}


def rec(k, fn):
    try:
        r[k] = fn()
    except BaseException as e:
        r[k] = '%s: %s' % (type(e).__name__, e)


def _listener():
    srv = socket.socket()
    srv.bind(('127.0.0.1', 0))
    srv.listen(8)
    srv.setblocking(False)
    return srv, srv.getsockname()


def _client(address):
    cli = socket.socket()
    cli.connect(address)
    cli.setblocking(False)
    return cli


# --- the headline: a real exchange over a real socket ----------------------

def echo_over_a_real_socket():
    async def main():
        srv, address = _listener()

        async def server():
            loop = asyncio.get_running_loop()
            conn, _addr = await loop.sock_accept(srv)
            data = await loop.sock_recv(conn, 1024)
            await loop.sock_sendall(conn, data.upper())
            conn.close()

        async def client():
            loop = asyncio.get_running_loop()
            cli = _client(address)
            await loop.sock_sendall(cli, b'hello')
            answer = await loop.sock_recv(cli, 1024)
            cli.close()
            return answer

        task = asyncio.ensure_future(server())
        answer = await client()
        await task
        srv.close()
        return answer

    return asyncio.run(main())


rec('echo_over_a_real_socket', echo_over_a_real_socket)


# --- THE PROBE A STRAIGHT-THROUGH LOOP CANNOT FAKE -------------------------

def two_clients_served_concurrently():
    """Two connections, and the second client speaks FIRST.  A loop that
    handled connections one at a time would answer in accept order; the trace
    below can only come out in speaking order if the handler for the first
    connection really suspended on its unready socket."""
    async def main():
        srv, address = _listener()
        trace = []

        async def handler(conn, name):
            loop = asyncio.get_running_loop()
            data = await loop.sock_recv(conn, 1024)
            trace.append('read %s' % name)
            await loop.sock_sendall(conn, data)
            conn.close()

        async def accept_two():
            loop = asyncio.get_running_loop()
            conns = []
            for name in ('first', 'second'):
                conn, _addr = await loop.sock_accept(srv)
                trace.append('accepted %s' % name)
                conns.append(asyncio.ensure_future(handler(conn, name)))
            return conns

        accepting = asyncio.ensure_future(accept_two())
        a = _client(address)
        b = _client(address)
        conns = await accepting

        loop = asyncio.get_running_loop()
        # b speaks first, so b must be served first.
        await loop.sock_sendall(b, b'from-b')
        trace.append('b sent')
        got_b = await loop.sock_recv(b, 1024)
        await loop.sock_sendall(a, b'from-a')
        trace.append('a sent')
        got_a = await loop.sock_recv(a, 1024)

        for handle in conns:
            await handle
        a.close()
        b.close()
        srv.close()
        return (trace, got_b, got_a)

    return asyncio.run(main())


rec('two_clients_served_concurrently', two_clients_served_concurrently)


# --- a timer must beat an idle socket --------------------------------------

def a_timer_fires_while_waiting_on_io():
    """A registered-but-silent socket must not let the loop wait forever: the
    wait ends at the first DEADLINE too.  A loop that passes None to select
    whenever nothing is ready looks correct until this case."""
    async def main():
        srv, _address = _listener()
        loop = asyncio.get_running_loop()
        fired = []
        loop.add_reader(srv, lambda: fired.append('socket'))
        started = time.monotonic()
        await asyncio.sleep(0.2)
        elapsed = time.monotonic() - started
        loop.remove_reader(srv)
        srv.close()
        return (fired, elapsed >= 0.15, elapsed < 5.0)

    return asyncio.run(main())


rec('a_timer_fires_while_waiting_on_io', a_timer_fires_while_waiting_on_io)


def the_loop_sleeps_rather_than_spins():
    """Wall time passes; CPU time does not.  A loop that polls in a tight
    circle would burn a comparable amount of both, so the ratio is the
    evidence that the wait is a real suspension."""
    async def main():
        srv, _address = _listener()
        loop = asyncio.get_running_loop()
        loop.add_reader(srv, lambda: None)
        wall0, cpu0 = time.monotonic(), time.process_time()
        await asyncio.sleep(0.3)
        wall = time.monotonic() - wall0
        cpu = time.process_time() - cpu0
        loop.remove_reader(srv)
        srv.close()
        return (wall >= 0.25, cpu < wall * 0.5)

    return asyncio.run(main())


rec('the_loop_sleeps_rather_than_spins', the_loop_sleeps_rather_than_spins)


