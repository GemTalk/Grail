def add_reader_fires_when_data_arrives():
    async def main():
        srv, address = _listener()
        cli = _client(address)
        loop = asyncio.get_running_loop()
        conn, _addr = await loop.sock_accept(srv)

        seen = asyncio.get_running_loop().create_future()
        loop.add_reader(conn, lambda: seen.done() or seen.set_result(conn.recv(64)))
        cli.sendall(b'knock')
        data = await seen
        loop.remove_reader(conn)

        conn.close()
        cli.close()
        srv.close()
        return data

    return asyncio.run(main())


