def sock_recv_requires_a_nonblocking_socket():
    """A blocking recv inside a cooperative loop stops every other task, not
    just its caller, so it is refused at the call site.

    Note the set_debug(True): CPython makes this check ONLY in debug mode and
    otherwise performs the blocking recv.  GRAIL REFUSES EITHER WAY -- a hang
    of the entire loop is not a thing to discover at runtime -- but the probe
    turns debug on so that both sides raise and the message can be compared.
    The always-on half cannot be probed here: under CPython it would hang."""
    async def main():
        srv, address = _listener()
        cli = _client(address)
        loop = asyncio.get_running_loop()
        loop.set_debug(True)
        conn, _addr = await loop.sock_accept(srv)
        conn.setblocking(True)
        try:
            await loop.sock_recv(conn, 1)
            return 'no error'
        except ValueError as e:
            return ('ValueError', str(e), loop.get_debug())
        finally:
            loop.set_debug(False)
            conn.close()
            cli.close()
            srv.close()

    return asyncio.run(main())


