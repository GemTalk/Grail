# AN ASGI APP, SERVED.
#
# This is the first fixture in which Grail runs a PROTOCOL rather than exercising
# a primitive.  Every probe below is one or more real HTTP requests over a real
# loopback socket into `grail.asgi.Server`, and what makes that worth having is
# that a wrong answer is almost never localised: a request that comes back with
# the right status, headers and body has already required accept to hand over a
# usable socket, readiness to fire, a partial read to be resumed, a partial
# write to be finished, a task to be scheduled and a keep-alive connection to
# park without stalling anything else.  The socket fixtures test those one at a
# time; this tests them composed, which is the only way the failure modes that
# come from composition show up at all.
#
# WHERE THE SERVER LIVES: src/python/stdlib/grail_asgi.py, in the bundled
# importable tree beside flask / django / asgiref rather than in the ``grail``
# package.  Not a style choice -- importing any submodule of ``grail`` corrupts
# this session's import state, so the next unrelated import fails.  That is a
# pre-existing bug (``import grail.gemstone`` does it on a clean checkout, and
# the identical file under a package named ``grailx`` is fine), found by putting
# the server there first: it broke 80 tests further down the same SUnit shard.
#
# WHY THERE IS A SERVER TO TEST, given that uvicorn cannot run yet.  uvicorn
# asks the loop for create_server(protocol_factory, ...) and Grail has no
# transports, so "run an ASGI app" looks blocked.  But ASGI is just
# `async def app(scope, receive, send)`, and accept/read/write already exist as
# sock_accept/sock_recv/sock_sendall.  Transports are how CPython's asyncio
# prefers to REACH those calls, not a precondition for them -- so the server
# under test here is written straight onto the socket coroutines.
#
# THE PROBE THAT MATTERS MOST is `two_clients_interleave`, for the same reason
# `two_clients_served_concurrently` mattered in asyncio_io.py: every other probe
# here would also pass on a server that ran each connection to completion before
# looking at the next, which is precisely the bug a cooperative loop invites.
# It is arranged so that the only way to produce the recorded answer is for a
# handler that is waiting on a slow client to yield and for another handler to
# run to completion in the gap.
#
# THE SECOND MOST INTERESTING is `keep_alive_then_a_second_request`.  A
# keep-alive connection is the one case where bytes for request N+1 arrive in
# the same read that finished request N, so a server with a per-request buffer
# discards them and then waits forever for a request it has already been sent.
# That bug cannot be reached by any single-request test.
#
# NOT COVERED, because the server does not claim it: TLS, HTTP/2, WebSocket,
# chunked request bodies (refused, and there is a probe for the refusal),
# streaming request bodies (delivered as one message), and timeouts.
#
# Everything here is ordinary CPython: asyncio, socket, and an ASGI app written
# to the published interface.  The server module itself is pure Python with no
# Grail-specific spelling, which is what lets this file be ground truth rather
# than a description of what Grail happens to do.
#
# EXPECTED was generated by RUNNING CPython 3.14.6.

