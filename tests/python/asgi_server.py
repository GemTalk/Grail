# --- keep-alive ------------------------------------------------------------

async def keep_alive_then_a_second_request():
    """TWO requests on ONE connection, and the second is sent immediately after
    the first response is read -- so its head very often arrives in the same
    read that completed the first response's body.  A server that buffers per
    request drops those bytes and then waits forever."""
    async def probe(loop, address):
        sock = await _connect(loop, address)
        try:
            out = []
            for path in ('/one', '/two'):
                await sock.send(_get(path))
                status, headers, body = await sock.read_response()
                out.append((status, body, dict(headers).get(b'connection')))
            return out
        finally:
            sock.close()
    return await _with_server(_text_app(), probe)


async def both_requests_pipelined_into_one_write():
    """Both requests in a SINGLE send, so the server certainly has request 2 in
    its buffer before it has answered request 1.  This is the read-ahead case
    stated as sharply as it can be."""
    async def probe(loop, address):
        sock = await _connect(loop, address)
        try:
            await sock.send(_get('/a') + _get('/b'))
            first = await sock.read_response()
            second = await sock.read_response()
            return first[0], second[0], first[2], second[2]
        finally:
            sock.close()
    return await _with_server(_text_app(), probe)


async def no_content_length_closes_the_connection():
    """A response with no content-length is framed by the CLOSE, so the server
    must not keep the connection open -- the client would wait for bytes that
    are never coming."""
    async def app(scope, receive, send):
        await send({'type': 'http.response.start', 'status': 200,
                    'headers': [(b'content-type', b'text/plain')]})
        await send({'type': 'http.response.body', 'body': b'unsized'})
    async def probe(loop, address):
        sock = await _connect(loop, address)
        try:
            await sock.send(_get('/'))
            status, headers, body = await sock.read_response()
            # Reading to EOF is how _read_response framed it, so getting the
            # body at all proves the server closed.
            return status, body, dict(headers).get(b'connection')
        finally:
            sock.close()
    return await _with_server(app, probe)


