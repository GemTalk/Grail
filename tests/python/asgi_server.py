# --- the headline: concurrency ---------------------------------------------

async def two_clients_interleave():
    """The probe a sequential server cannot pass.

    The app waits for a per-path event.  Client SLOW connects first and its
    handler parks; client FAST connects second and is released immediately.  The
    recorded answer is the completion ORDER, so serving in arrival order --
    which is what a server that runs each connection to completion does --
    produces ['slow', 'fast'] instead."""
    released = {}

    async def app(scope, receive, send):
        name = scope['path'].strip('/')
        await released[name]
        body = name.encode('ascii')
        await send({'type': 'http.response.start', 'status': 200,
                    'headers': [(b'content-length',
                                 str(len(body)).encode('ascii'))]})
        await send({'type': 'http.response.body', 'body': body})

    async def probe(loop, address):
        # A Future rather than the asyncio.Event this obviously wants: Grail's
        # asyncio has no Event yet (nor Lock / Semaphore / Queue -- the next
        # small increment).  A Future awaited once and resolved once is the same
        # guarantee here, and it is ordinary CPython either way, so the probe
        # stays valid ground truth.
        released['slow'] = loop.create_future()
        released['fast'] = loop.create_future()
        order = []

        async def client(name):
            _s, _h, body = await _request(loop, address, _get('/' + name))
            order.append(body.decode('ascii'))

        slow = asyncio.get_event_loop().create_task(client('slow'))
        # Let the slow client connect and its handler reach the wait before the
        # fast one exists at all, so arrival order and completion order differ.
        await asyncio.sleep(0.05)
        fast = asyncio.get_event_loop().create_task(client('fast'))
        await asyncio.sleep(0.05)
        released['fast'].set_result(True)
        await fast
        released['slow'].set_result(True)
        await slow
        return order
    return await _with_server(app, probe)


async def many_clients_are_all_served():
    """Eight concurrent connections, each asking for its own path.  Asserts the
    SET of answers, not the order: the order is a scheduling detail and pinning
    it would be pinning local timing, which has already cost this repo three CI
    failures."""
    async def app(scope, receive, send):
        body = scope['path'].strip('/').encode('ascii')
        await asyncio.sleep(0)      # force at least one yield per handler
        await send({'type': 'http.response.start', 'status': 200,
                    'headers': [(b'content-length',
                                 str(len(body)).encode('ascii'))]})
        await send({'type': 'http.response.body', 'body': body})

    async def probe(loop, address):
        async def one(n):
            _s, _h, body = await _request(loop, address, _get('/%d' % n))
            return body.decode('ascii')
        results = await asyncio.gather(*[one(n) for n in range(8)])
        return sorted(results)
    return await _with_server(app, probe)


