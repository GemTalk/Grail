async def an_app_that_raises_mid_response_drops_the_connection():
    """Once the head is out a 500 is impossible -- the status has been sent.  So
    the connection ends, which is the only signal left that says "incomplete"."""
    async def app(scope, receive, send):
        await send({'type': 'http.response.start', 'status': 200,
                    'headers': [(b'content-length', b'100')]})
        await send({'type': 'http.response.body', 'body': b'partial',
                    'more_body': True})
        raise RuntimeError('boom')
    async def probe(loop, address):
        sock = await _connect(loop, address)
        try:
            await sock.send(_get('/'))
            got = bytearray()
            while True:
                chunk = await sock.recv_raw(65536)
                if not chunk:
                    break
                got.extend(chunk)
            head, _, body = bytes(got).partition(b'\r\n\r\n')
            return head.split(b'\r\n')[0], body, len(body) < 100
        finally:
            sock.close()
    return await _with_server(app, probe)


