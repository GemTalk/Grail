# --- a client, written on the same loop as the server ----------------------
#
# Deliberately NOT the blocking socket module and not http.client: those would
# need a thread to run alongside the server, and on Grail's cooperative loop a
# blocking read is a stalled gem rather than a stalled thread.  Driving both
# ends from the one loop is also a stronger test -- it means the server has to
# yield for the client to make progress at all.

class _Conn:
    """A client connection with a buffer that OUTLIVES one response.

    The buffer has to live on the connection rather than in the read call, and
    the reason is the same one that applies to the server: on a keep-alive
    connection the read that completes response N routinely also contains the
    start of response N+1.  A per-call buffer discards those bytes and then
    waits forever for a response it has already received.

    This was not a hypothesis.  The first version of this helper did buffer
    per call, and `both_requests_pipelined_into_one_write` hung under CPython --
    which is a fair result for a probe written to catch exactly that mistake,
    just on the wrong side of the socket."""

    def __init__(self, loop, sock):
        self.loop = loop
        self.sock = sock
        self.buf = bytearray()

    async def send(self, raw):
        await self.loop.sock_sendall(self.sock, raw)

    async def _fill(self):
        """Read more; answer False at EOF."""
        chunk = await self.loop.sock_recv(self.sock, 65536)
        if not chunk:
            return False
        self.buf.extend(chunk)
        return True

    async def read_response(self):
        """Read one complete response; answer (status, headers, body).

        Completeness is decided by content-length when there is one and by EOF
        when there is not -- exactly the rule the server writes to, see
        Server._should_keep_alive.  A client that guessed differently would
        hang on a perfectly correct response."""
        while True:
            end = bytes(self.buf).find(b'\r\n\r\n')
            if end >= 0:
                break
            if not await self._fill():
                raise AssertionError('closed inside the response head')
        head = bytes(self.buf[:end])
        del self.buf[:end + 4]
        lines = head.split(b'\r\n')
        status = int(lines[0].split(b' ')[1])
        headers = []
        for line in lines[1:]:
            if line:
                name, _, value = line.partition(b':')
                headers.append((name.lower(), value.strip()))
        length = None
        for name, value in headers:
            if name == b'content-length':
                length = int(value)
        if length is None:
            # Framed by the close, so read to EOF.
            while await self._fill():
                pass
            body = bytes(self.buf)
            del self.buf[:]
            return status, headers, body
        while len(self.buf) < length:
            if not await self._fill():
                raise AssertionError('closed inside the response body')
        body = bytes(self.buf[:length])
        del self.buf[:length]
        return status, headers, body

    async def recv_raw(self, n):
        """Whatever is buffered, else one read.  Used only where a probe is
        asking whether the server closed."""
        if self.buf:
            out = bytes(self.buf[:n])
            del self.buf[:n]
            return out
        return await self.loop.sock_recv(self.sock, n)

    def close(self):
        self.sock.close()


async def _connect(loop, address):
    sock = socket.socket()
    sock.setblocking(False)
    await loop.sock_connect(sock, address)
    return _Conn(loop, sock)


async def _request(loop, address, raw):
    """One request on a fresh connection; answer (status, headers, body)."""
    conn = await _connect(loop, address)
    try:
        await conn.send(raw)
        return await conn.read_response()
    finally:
        conn.close()


def _get(path='/', host='x'):
    return ('GET %s HTTP/1.1\r\nhost: %s\r\n\r\n' % (path, host)).encode('ascii')


# --- apps ------------------------------------------------------------------

def _text_app(body=b'hello', status=200, extra=()):
    """The ordinary shape: one start, one body, a content-length."""
    async def app(scope, receive, send):
        await receive()
        headers = [(b'content-type', b'text/plain'),
                   (b'content-length', str(len(body)).encode('ascii'))]
        headers.extend(extra)
        await send({'type': 'http.response.start', 'status': status,
                    'headers': headers})
        await send({'type': 'http.response.body', 'body': body})
    return app


def _echo_scope_app(keys):
    """Answers the requested scope keys, one per line, so a probe can assert on
    what the app actually saw rather than on what the server logged."""
    async def app(scope, receive, send):
        parts = []
        for key in keys:
            parts.append('%s=%r' % (key, scope.get(key)))
        body = ('\n'.join(parts)).encode('utf-8')
        await send({'type': 'http.response.start', 'status': 200,
                    'headers': [(b'content-length',
                                 str(len(body)).encode('ascii'))]})
        await send({'type': 'http.response.body', 'body': body})
    return app


async def _with_server(app, fn, **kw):
    """Start a server, run fn(loop, address), stop it.  Always stops -- a
    leaked listener would make the NEXT probe fail, which is the worst kind of
    test failure to read."""
    loop = asyncio.get_event_loop()
    server = Server(app, host='127.0.0.1', port=0, **kw)
    address = await server.start()
    try:
        return await fn(loop, address)
    finally:
        await server.stop()


