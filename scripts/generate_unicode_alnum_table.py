#!/usr/bin/env python3
"""Generate src/c/shim/grail_alnum_table.h -- the Unicode alphanumeric ranges
the CPython shim's _grail_unicode_isalnum needs, which is what a regular
expression's ``\\w`` matches (with ``_``) and ``\\W`` and ``\\b`` exclude.

Authoritative source: CPython's own str.isalnum(), which applies
Py_UNICODE_ISALNUM to each character (Objects/unicodeobject.c:12294,
unicode_isalnum_impl).  That is the predicate _sre's SRE_UNI_IS_ALNUM is
(Modules/_sre/sre.c:169), and it is alpha OR decimal OR digit OR numeric
(Include/cpython/unicodeobject.h:762), so a table of str.isalnum() is exactly
what CPython's ``\\w'' tests.

The shim keeps an ASCII fast path, so only code points >= 128 are tabulated.
Letters come in long runs, which is why this is a range table.

Run with the SAME CPython version Grail vendors (3.14.x):
    python3.14 scripts/generate_unicode_alnum_table.py
"""
import sys
import unicodedata

OUT = "src/c/shim/grail_alnum_table.h"
MAX = 0x110000


def alnum_ranges():
    ranges = []
    for codepoint in range(128, MAX):
        if not chr(codepoint).isalnum():
            continue
        if ranges and codepoint == ranges[-1][1] + 1:
            ranges[-1][1] = codepoint
        else:
            ranges.append([codepoint, codepoint])
    return ranges


def main():
    ranges = alnum_ranges()

    with open(OUT, "w") as f:
        f.write("/* GENERATED by scripts/generate_unicode_alnum_table.py"
                " -- do not edit.\n")
        f.write(" * Source: CPython %s str.isalnum(), which is"
                " Py_UNICODE_ISALNUM per character.\n" % sys.version.split()[0])
        f.write(" * Unicode %s.  Non-ASCII only; ASCII is isalnum() in"
                " the shim.\n" % unicodedata.unidata_version)
        f.write(" * Sorted and non-adjacent {first, last} pairs, so a binary"
                " search decides membership. */\n\n")
        f.write("static const unsigned int grail_alnum_ranges[][2] = {\n")
        for index in range(0, len(ranges), 4):
            row = "".join("{0x%05x,0x%05x}," % (first, last)
                          for first, last in ranges[index:index + 4])
            f.write("    " + row + "\n")
        f.write("};\n")
        f.write("static const int grail_alnum_ranges_len = %d;\n"
                % len(ranges))

    print("wrote %s: %d ranges, %d code points"
          % (OUT, len(ranges),
             sum(last - first + 1 for first, last in ranges)))


if __name__ == "__main__":
    main()
