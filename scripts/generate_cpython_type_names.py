#!/usr/bin/env python3
"""Regenerate ``Object class >> ___cpythonDottedTypeNames___`` (environment 1) in
src/Grail-Kernel-PyEnv/Object.extension.st: the stdlib types whose CPython
``tp_name`` names their module.

CPython's error messages print a type's ``tp_name`` -- ``'collections.deque'
object has no attribute 'x'``, ``cannot set 'x' attribute of immutable type
'types.SimpleNamespace'`` -- and ``tp_name`` is NOT ``__name__``.  A class
statement's is the bare name; a type implemented in C, static or built by
PyType_FromSpec, carries the dotted name its C source gives it.  Nothing
reachable from Python says which a type is, so this asks CPython itself: every
type reachable from a stdlib module (and one class level below it) is probed
for the one message that prints a type object's tp_name, ``type object
'<tp_name>' has no attribute ...``, and kept when that differs from its
``__name__``.

Every name kept is ``__module__ + '.' + __qualname__`` -- the script stops if
one is not -- which is what lets Grail recompute tp_name from attributes it
already answers correctly, without a second table of names to keep in step.

Run with the SAME CPython version Grail vendors (3.14.x):
    ~/Documents/cpython-build-3.14.8/python.exe -I scripts/generate_cpython_type_names.py
"""
import importlib
import os
import pkgutil
import re
import sys
import warnings

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tonel_methods import Method, set_methods  # noqa: E402

TONEL = os.path.join(HERE, "..", "src", "Grail-Kernel-PyEnv", "Object.extension.st")
MODULES = os.path.join(HERE, "cpython_314_stdlib_modules.txt")

# Modules whose import does something (opens a browser, prints, needs a
# display) or that exist only on Windows.
SKIP = {'antigravity', 'this', 'idlelib', 'tkinter', 'turtle', 'turtledemo', '__phello__',
        '_tkinter', 'pydoc_data', 'ensurepip', 'venv', '_pyrepl', 'msvcrt', 'winreg',
        'winsound', '_winapi', 'nt', '_wmi', '_overlapped'}


def module_names():
    top = [line.strip() for line in open(MODULES)
           if line.strip() and not line.startswith('#')]
    for name in top:
        if name in SKIP:
            continue
        yield name
        try:
            package = importlib.import_module(name)
        except BaseException:
            continue
        if hasattr(package, '__path__'):
            for info in pkgutil.walk_packages(package.__path__, name + '.'):
                if not any(part in info.name for part in ('.test', 'tests', '__main__')):
                    yield info.name


def reachable_types(module):
    pool = [v for v in vars(module).values() if isinstance(v, type)]
    for value in list(pool):
        pool.extend(v for v in vars(value).values() if isinstance(v, type))
    return pool


def tp_name(cls):
    try:
        type.__getattribute__(cls, '__grail_tp_name_probe__')
    except AttributeError as e:
        found = re.match(r"type object '(.*)' has no attribute", str(e))
        return found.group(1) if found else None
    return None


def dotted_type_names():
    names = set()
    for name in module_names():
        try:
            module = importlib.import_module(name)
        except BaseException:
            continue
        for cls in reachable_types(module):
            printed = tp_name(cls)
            if printed is None or printed == cls.__name__:
                continue
            qualified = '%s.%s' % (cls.__module__, cls.__qualname__)
            if printed != qualified:
                sys.exit('%s prints as %s, not module.qualname' % (qualified, printed))
            names.add(qualified)
    return sorted(names)


def main():
    warnings.simplefilter('ignore')
    names = dotted_type_names()
    lines = ["___cpythonDottedTypeNames___",
             "\t\"The stdlib types whose CPython tp_name names their module, as",
             "\t``module.qualname'' -- see ___pyTpName___.  %d of them." % len(names),
             "",
             "\tGENERATED by scripts/generate_cpython_type_names.py from CPython %d.%d.%d --"
             % sys.version_info[:3],
             "\tdo not edit by hand.\"",
             "",
             "\t^ #("]
    lines += ["\t\t'%s'" % name for name in names]
    lines[-1] += " )"
    set_methods(TONEL, "Object", [
        Method(meta=True, category="Grail-Error Messages", source="\n".join(lines) + "\n")])
    print("wrote %d type names into %s" % (len(names), os.path.relpath(TONEL)))


if __name__ == "__main__":
    main()
