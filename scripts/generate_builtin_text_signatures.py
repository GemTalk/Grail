#!/usr/bin/env python3
"""Regenerate src/python/stdlib/_grail_text_signatures.py from CPython's own
``__text_signature__`` of the builtins.

A C-implemented callable carries its parameter list as text -- ``len`` has
``($module, obj, /)``, ``str.split`` ``($self, /, sep=None, maxsplit=-1)``,
``list`` ``(iterable=(), /)`` -- and inspect.signature() reads it.  Some have
none (``dict``, ``max``, ``dir``), and for those signature() raises
``ValueError: no signature found for builtin ...``.  Grail's builtins are
Smalltalk methods with no such text, so signature() answered ``()`` for every
one of them: rlcompleter then completed ``str.split()`` and ``dict()``, and
anything that introspects a builtin saw no parameters.

The table maps each builtin's ``__qualname__`` -- the builtins module's
functions, and every type in it with the methods its ``__dict__`` holds -- to
its text, or to None for one that has none, so that "known to have none" and
"not a builtin" stay two answers.  Grail's inspect.signature reads it.

Run with the SAME CPython version Grail vendors (3.14.x):
    ~/Documents/cpython-build-3.14.8/python.exe -I scripts/generate_builtin_text_signatures.py
"""
import builtins
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "src", "python", "stdlib", "_grail_text_signatures.py")
CALLABLE_KINDS = (types.BuiltinFunctionType, types.MethodDescriptorType,
                  types.WrapperDescriptorType, types.ClassMethodDescriptorType)
SINGLETON_TYPES = (type(None), type(Ellipsis), type(NotImplemented))


def entries():
    table = {}
    for name, value in vars(builtins).items():
        if isinstance(value, types.BuiltinFunctionType) and not name.startswith('_'):
            table[value.__qualname__] = value.__text_signature__
    for value in vars(builtins).values():
        if not isinstance(value, type):
            continue
        table[value.__qualname__] = value.__text_signature__
        for attribute in vars(value).values():
            if isinstance(attribute, CALLABLE_KINDS):
                table[attribute.__qualname__] = attribute.__text_signature__
    # The singletons' types, which builtins does not name: None's methods are
    # what rlcompleter completes ``None.'' from.  Keyed by the TYPE's name and
    # each name dir() lists, inherited ones too -- Grail answers every method of
    # None with a ``NoneType.'' qualname, where CPython's inherited ones say
    # ``object.''.
    for value in SINGLETON_TYPES:
        table[value.__qualname__] = value.__text_signature__
        for name in dir(value):
            attribute = getattr(value, name)
            if isinstance(attribute, CALLABLE_KINDS):
                table['%s.%s' % (value.__qualname__, name)] = attribute.__text_signature__
    return table


def main():
    table = entries()
    lines = ['"""The __text_signature__ of each builtin, by __qualname__ -- None for one',
             'that has none.  %d of them.' % len(table),
             '',
             'GENERATED by scripts/generate_builtin_text_signatures.py from CPython %d.%d.%d --'
             % sys.version_info[:3],
             'do not edit by hand.  Read by inspect.signature for the builtins, whose',
             'Grail implementations carry no text of their own.',
             '"""',
             '',
             'TEXT_SIGNATURES = {']
    lines += ['    %r: %r,' % (name, table[name]) for name in sorted(table)]
    lines.append('}')
    with open(TARGET, 'w') as out:
        out.write('\n'.join(lines) + '\n')
    print("wrote %d text signatures into %s" % (len(table), os.path.relpath(TARGET)))


if __name__ == "__main__":
    main()
